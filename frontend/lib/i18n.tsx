type Ctx = { lang: Lang; setLang: (l: Lang) => void; t: (k: string) => string };
const LangCtx = createContext<Ctx>({ lang: 'bn', setLang: () => {}, t: (k) => k });

export function LangProvider({ children }: { children: ReactNode }) {
  const [lang, setLangState] = useState<Lang>('bn');
  useEffect(() => {
    try { const l = localStorage.getItem('ml_lang'); if (l === 'en' || l === 'bn') setLangState(l); } catch {}
  }, []);
  useEffect(() => { document.documentElement.lang = lang === 'bn' ? 'bn' : 'en'; }, [lang]);
  const setLang = (l: Lang) => { setLangState(l); try { localStorage.setItem('ml_lang', l); } catch {} };
  const t = (k: string) => (S[k] ? S[k][lang === 'bn' ? 0 : 1] : k);
  return <LangCtx.Provider value={{ lang, setLang, t }}>{children}</LangCtx.Provider>;
}

export const useT = () => useContext(LangCtx);
